/* Regenerates world/manifest.json from the scene files.
 *
 * The manifest is the world's memory. Each growth run is a fresh session with
 * no recollection of the last one, so what the job knows about the world is
 * exactly what this file says. Output is deterministic — no timestamps — so a
 * run that changes nothing produces no diff.
 *
 *   node tools/build-manifest.mjs
 */

import { readFile, writeFile, readdir } from 'node:fs/promises';
import { join } from 'node:path';

const SCENES = 'world/scenes';
const OUT = 'world/manifest.json';
export const ENTRY = 'hall-of-doors';

export async function readScenes() {
  const files = (await readdir(SCENES))
    .filter((f) => f.endsWith('.json'))
    .sort();

  const scenes = [];
  for (const file of files) {
    const raw = await readFile(join(SCENES, file), 'utf8');
    let data;
    try {
      data = JSON.parse(raw);
    } catch (err) {
      throw new Error(`${SCENES}/${file}: invalid JSON — ${err.message}`);
    }
    scenes.push({ file, data });
  }
  return scenes;
}

function summarise(scene) {
  const spots = scene.hotspots || [];
  const kind = (k) => spots.filter((s) => s.action === k);

  return {
    id: scene.id,
    title: scene.title,
    region: scene.region || 'unassigned',
    craft: scene.craft ?? 2,
    exits: kind('goto').map((s) => s.target).sort(),
    frontiers: kind('frontier').map((s) => ({ shape: s.shape, hint: s.hint })),
    interactions: kind('animate').length + kind('text').length,
    sets: spots.map((s) => s.sets).filter(Boolean).sort(),
    requires: spots.map((s) => s.requires).filter(Boolean).sort(),
  };
}

export async function buildManifest() {
  const scenes = (await readScenes()).map(({ data }) => data);
  const summaries = scenes.map(summarise);

  const frontier = [];
  for (const s of summaries) {
    for (const f of s.frontiers) {
      frontier.push({ scene: s.id, shape: f.shape, hint: f.hint });
    }
  }

  const regions = [...new Set(summaries.map((s) => s.region))].sort();

  // Mean craft is what keeps polish pacing with growth. Every new scene lands
  // at 2 and drags it down; every ENRICH run lifts it back. GROW.md reads this
  // number to decide whether today is for building or for drawing.
  const craftMean = summaries.length
    ? Number((summaries.reduce((n, s) => n + s.craft, 0) / summaries.length).toFixed(2))
    : 0;

  // The next scene an ENRICH run should take: lowest rung first, and among
  // equals the one that has waited longest (scenes are read in sorted order).
  const nextEnrich = [...summaries]
    .filter((s) => s.craft < 5)
    .sort((a, b) => a.craft - b.craft)[0];

  return {
    _comment: 'Generated by tools/build-manifest.mjs. Do not edit by hand.',
    entry: ENTRY,
    counts: {
      scenes: summaries.length,
      regions: regions.length,
      exits: summaries.reduce((n, s) => n + s.exits.length, 0),
      interactions: summaries.reduce((n, s) => n + s.interactions, 0),
      frontiers: frontier.length,
      craftMean,
    },
    regions,
    nextEnrich: nextEnrich
      ? { scene: nextEnrich.id, craft: nextEnrich.craft, raiseTo: nextEnrich.craft + 1 }
      : null,
    scenes: summaries,
    frontier,
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const manifest = await buildManifest();
  await writeFile(OUT, JSON.stringify(manifest, null, 2) + '\n');
  const c = manifest.counts;
  console.log(
    `manifest: ${c.scenes} scenes, ${c.regions} regions, ${c.exits} exits, ` +
    `${c.interactions} interactions, ${c.frontiers} open frontiers, ` +
    `craft ${c.craftMean}`
  );
}
